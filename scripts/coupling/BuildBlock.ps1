function Build-RecommendationBlock($Target) {
  $sizes=@($Target.sizes_mm)
  $a=Convert-ToPersianDigits([string]$sizes[0])
  $kind=[string]$Target.kind
  $profile=[string]$Target.profile

  if($kind -eq 'equal_tee') {
    $heading="قطعات پیشنهادی برای سه‌راه مساوی پلی‌اتیلن $a میلی‌متر"
    $intro="این سه‌راه برای ایجاد انشعاب در خط پلی‌اتیلن هم‌سایز $a میلی‌متری استفاده می‌شود. برای اینکه مسیر اصلی و شاخه انشعاب ناقص نماند، لوله و چند قطعه کاربردی هم‌سایز از محصولات واقعی فروشگاه در ادامه پیشنهاد شده‌اند."
    $beforeBuy="هر سه دهانه پلی‌اتیلن را با سایز $a میلی‌متر خط موجود تطبیق دهید و برای شاخه جدید، طول لوله و قطعات انتهایی مورد نیاز را هم در نظر بگیرید."
  } elseif($kind -eq 'female_tee') {
    $heading="لوازم پیشنهادی برای سه‌راه ماده پلی‌اتیلن $a میلی‌متر"
    $intro="این مدل روی خط پلی‌اتیلن $a میلی‌متری نصب می‌شود و یک خروجی رزوه ماده برای گرفتن انشعاب رزوه‌ای دارد. پیشنهادهای زیر فقط برای بخش پلی‌اتیلن و از محصولات واقعی هم‌سایز فروشگاه انتخاب شده‌اند؛ اندازه رزوه خروجی از قطر لوله حدس زده نشده است."
    $beforeBuy="سایز $a میلی‌متر را برای مسیر پلی‌اتیلن کنترل کنید و اندازه و نوع رزوه خروجی ماده را جداگانه با قطعه نر مقابل تطبیق دهید. سایز لوله و سایز رزوه دو مشخصه مستقل هستند."
  } elseif($kind -eq 'male_tee') {
    $heading="لوازم پیشنهادی برای سه‌راه نر پلی‌اتیلن $a میلی‌متر"
    $intro="این مدل روی خط پلی‌اتیلن $a میلی‌متری نصب می‌شود و یک خروجی رزوه نر برای انشعاب رزوه‌ای دارد. پیشنهادهای زیر برای تکمیل بخش پلی‌اتیلن و فقط از محصولات واقعی هم‌سایز فروشگاه انتخاب شده‌اند؛ اندازه رزوه خروجی از قطر لوله استنتاج نشده است."
    $beforeBuy="سایز $a میلی‌متر را برای مسیر پلی‌اتیلن کنترل کنید و اندازه و نوع رزوه خروجی نر را جداگانه با قطعه مادگی مقابل تطبیق دهید."
  } elseif($kind -eq 'reducer_tee') {
    $b=Convert-ToPersianDigits([string]$sizes[1])
    $heading="قطعات پیشنهادی برای سه‌راه تبدیل پلی‌اتیلن $a و $b میلی‌متر"
    $intro="این سه‌راه بیش از یک سایز پلی‌اتیلن دارد و برای ایجاد انشعاب یا اتصال بخش‌هایی با قطر متفاوت استفاده می‌شود. پیشنهادهای زیر برای هر دو سایز $a و $b میلی‌متر از محصولات واقعی فروشگاه انتخاب شده‌اند. جای هر سایز روی بدنه سه‌راه را دقیقاً با عنوان، تصویر و مشخصات همان محصول تطبیق دهید."
    $beforeBuy="فقط به بزرگ‌تر یا کوچک‌تر بودن اعداد تکیه نکنید؛ مشخص کنید هر سایز مربوط به کدام دهانه است و سپس لوله و اتصال همان سمت را انتخاب کنید."
  } elseif($kind -eq 'reducer'){
    $b=Convert-ToPersianDigits([string]$sizes[1])
    $heading="قطعات پیشنهادی برای تکمیل خط پلی‌اتیلن $a به $b میلی‌متر"
    $intro="این رابط تبدیل بین دو سایز $a و $b میلی‌متر قرار می‌گیرد. برای اینکه سفارش ناقص نماند، پیشنهادهای زیر بر اساس هر دو سمت اتصال و فقط از محصولات واقعی فروشگاه انتخاب شده‌اند. هر سمت را جداگانه با سایز درج‌شده روی لوله یا اتصال موجود تطبیق دهید."
    $beforeBuy="مبنا را سایز میلی‌متری هر دو سمت قرار دهید و دو طرف اتصال را جداگانه تطبیق دهید."
  } elseif($kind -eq 'male_thread') {
    $heading="لوازم پیشنهادی برای زانو پلی‌اتیلن یکسر نر $a میلی‌متر"
    $intro="در این مدل، یک سمت برای خط پلی‌اتیلن $a میلی‌متری است و سمت دیگر رزوه نر دارد. پیشنهادهای زیر فقط برای سمت پلی‌اتیلن و بر اساس محصولات واقعی هم‌سایز فروشگاه انتخاب شده‌اند؛ اندازه رزوه از روی سایز لوله حدس زده نشده است."
    $beforeBuy="سایز $a میلی‌متر را برای سمت لوله بررسی کنید و اندازه و نوع رزوه سمت نر را جداگانه با قطعه مقابل تطبیق دهید. عدد میلی‌متری لوله، به‌تنهایی اندازه رزوه را تعیین نمی‌کند."
  } elseif($kind -eq 'female_thread') {
    $heading="لوازم پیشنهادی برای زانو پلی‌اتیلن یکسر ماده $a میلی‌متر"
    $intro="در این مدل، یک سمت برای خط پلی‌اتیلن $a میلی‌متری است و سمت دیگر رزوه ماده دارد. پیشنهادهای زیر برای سمت پلی‌اتیلن و از محصولات واقعی هم‌سایز فروشگاه انتخاب شده‌اند. برای سمت رزوه، همان اندازه‌ای را ملاک قرار دهید که در عنوان محصول و روی اتصال مقابل درج شده است."
    $beforeBuy="سایز $a میلی‌متر را برای سمت لوله و سایز رزوه را برای سمت ماده به‌صورت مستقل کنترل کنید؛ این دو مشخصه را به‌جای یکدیگر استفاده نکنید."
  } elseif($kind -eq 'male_adapter') {
    $heading="لوازم پیشنهادی برای اتصال نر پلی‌اتیلن $a میلی‌متر"
    $intro="این اتصال یک سمت پیچی برای لوله پلی‌اتیلن $a میلی‌متری و یک سمت نر برای اتصال به قطعه مقابل دارد. پیشنهادهای زیر فقط بر اساس سمت پلی‌اتیلن و محصولات واقعی هم‌سایز فروشگاه انتخاب شده‌اند؛ اندازه سمت رزوه‌ای از قطر لوله حدس زده نشده است."
    $beforeBuy="سایز $a میلی‌متر را برای سمت لوله کنترل کنید و اندازه و نوع رزوه نر را جداگانه با رزوه مادگی قطعه مقابل تطبیق دهید. اندازه لوله و اندازه رزوه دو مشخصه مستقل هستند."
  } elseif($kind -eq 'female_adapter') {
    $heading="لوازم پیشنهادی برای اتصال ماده پلی‌اتیلن $a میلی‌متر"
    $intro="این اتصال یک سمت پیچی برای لوله پلی‌اتیلن $a میلی‌متری و یک سمت ماده برای اتصال به قطعه مقابل دارد. پیشنهادهای زیر برای تکمیل سمت پلی‌اتیلن و فقط از محصولات واقعی هم‌سایز فروشگاه انتخاب شده‌اند؛ اندازه سمت رزوه‌ای از قطر لوله استنتاج نشده است."
    $beforeBuy="سایز $a میلی‌متر را برای سمت لوله کنترل کنید و اندازه و نوع رزوه ماده را جداگانه با رزوه نر قطعه مقابل تطبیق دهید. اندازه لوله را جای اندازه رزوه در نظر نگیرید."
  } elseif($kind -eq 'flanged_adapter') {
    $heading="لوازم پیشنهادی برای اتصال فلنج‌دار پلی‌اتیلن $a میلی‌متر"
    $intro="این اتصال برای متصل کردن خط پلی‌اتیلن $a میلی‌متری به بخش فلنجی سیستم استفاده می‌شود. پیشنهادهای زیر برای سمت پلی‌اتیلن و از محصولات واقعی هم‌سایز فروشگاه انتخاب شده‌اند؛ مشخصات سمت فلنج باید جداگانه با فلنج مقابل تطبیق داده شود."
    $beforeBuy="سایز $a میلی‌متر را برای سمت پلی‌اتیلن بررسی کنید و در سمت فلنج، سایز فلنج مقابل، الگوی پیچ‌ها و آب‌بندی مورد نیاز را مستقل کنترل کنید."
  } elseif($profile -eq 'elbow') {
    $heading="قطعات پیشنهادی برای زانو پلی‌اتیلن $a میلی‌متر"
    $intro="این اتصال برای تغییر مسیر خط پلی‌اتیلن هم‌سایز $a میلی‌متری استفاده می‌شود. برای تکمیل همان شاخه، لوله و چند قطعه کاربردی هم‌سایز از محصولات واقعی فروشگاه در ادامه آمده‌اند."
    $beforeBuy="مبنای انتخاب را سایز میلی‌متری لوله پلی‌اتیلن قرار دهید و دو سر اتصال را با خط موجود تطبیق دهید."
  } else {
    $heading="قطعات پیشنهادی برای تکمیل خط پلی‌اتیلن $a میلی‌متر"
    $intro="این اتصال برای خط پلی‌اتیلن $a میلی‌متری انتخاب شده است. برای تکمیل سفارش، لوله و چند قطعه کاربردی هم‌سایز از محصولات واقعی فروشگاه در ادامه آمده‌اند."
    $beforeBuy="مبنای انتخاب را سایز میلی‌متری لوله و نوع واقعی دو سر اتصال قرار دهید."
  }

  $items=@()
  foreach($r in @($Target.proposed_products)){
    $s=Convert-ToPersianDigits([string]$r.side_mm)
    $label=switch([string]$r.family){
      'pipe'{"لوله پلی‌اتیلن $s میلی‌متر"}
      'coupling'{"رابط مستقیم پلی‌اتیلن $s میلی‌متر"}
      'endcap'{"درپوش انتهایی $s میلی‌متر"}
      'elbow'{"زانو پلی‌اتیلن $s میلی‌متر"}
      'tee'{"سه‌راه پلی‌اتیلن $s میلی‌متر"}
      'valve'{"شیر هم‌سایز $s میلی‌متر"}
      default{"اتصال $s میلی‌متر"}
    }
    $note=switch([string]$r.family){
      'pipe'{"برای ادامه مسیر یا ساخت شاخه پلی‌اتیلن $s میلی‌متری."}
      'coupling'{'برای ادامه مستقیم بخش دیگری از همان خط.'}
      'endcap'{'برای بستن انتهای یک شاخه هم‌سایز.'}
      'elbow'{'برای تغییر مسیر بخش دیگری از همان خط.'}
      'tee'{'برای ایجاد انشعاب در همان سایز.'}
      'valve'{'برای کنترل جریان در یک بخش هم‌سایز؛ نوع اتصال دو سر شیر نیز باید جداگانه تطبیق داده شود.'}
      default{'برای تکمیل همان شاخه.'}
    }
    $name=[Net.WebUtility]::HtmlEncode([string]$r.name)
    $url=[Net.WebUtility]::HtmlEncode([string]$r.permalink)
    $items+=('<li style="margin:7px 0"><strong>{0}:</strong> <a style="color:#176b3a;font-weight:700" href="{1}">{2}</a> — {3}</li>' -f $label,$url,$name,$note)
  }

  $missing=@($Target.missing_pipe_sizes)
  $missingText=''
  if($missing.Count){
    $m=@($missing|ForEach-Object{Convert-ToPersianDigits([string]$_)})-join' و '
    $missingText="<p><strong>نکته:</strong> برای سایز $m میلی‌متر، لوله پلی‌اتیلن منتشرشده‌ای در دسته لوله‌های فروشگاه پیدا نشد؛ بنابراین لینک ساختگی یا سایز نامرتبط پیشنهاد نشده است.</p>"
  }

  $typeNote=''
  if($kind -in @('male_thread','female_thread','male_adapter','female_adapter','male_tee','female_tee')){
    $typeNote='<p><strong>نکته اتصال رزوه‌ای:</strong> هم‌سایز بودن بخش پلی‌اتیلن به معنی سازگاری خودکار رزوه نیست. نوع نر یا ماده و اندازه واقعی رزوه قطعه مقابل را جداگانه کنترل کنید.</p>'
  } elseif($kind -eq 'flanged_adapter') {
    $typeNote='<p><strong>نکته اتصال فلنجی:</strong> هم‌سایز بودن لوله پلی‌اتیلن به‌تنهایی سازگاری دو فلنج را تضمین نمی‌کند؛ مشخصات فلنج مقابل و متعلقات آب‌بندی باید جداگانه تطبیق داده شوند.</p>'
  } elseif($kind -eq 'reducer_tee') {
    $typeNote='<p><strong>نکته سه‌راه تبدیلی:</strong> در سه‌راه‌های چندسایز، محل قرارگیری هر قطر مهم است. قبل از سفارش مشخص کنید کدام دهانه به خط اصلی و کدام دهانه به انشعاب متصل می‌شود.</p>'
  }

  $list=$items-join"`n"
  return @"
<h2 style="font-size:24px;line-height:1.8;color:#176b3a;margin:34px 0 14px;border-right:5px solid #5d9a68;padding-right:12px">$heading</h2>
<div style="background:#f7fbf8;border:1px solid #dbe8df;border-radius:16px;padding:17px;margin:15px 0">
<p>$intro</p>
<ul style="padding-right:22px;margin:10px 0">$list</ul>
$missingText
$typeNote
<p style="margin:12px 0 0"><strong>قبل از خرید:</strong> $beforeBuy</p>
</div>
"@
}
