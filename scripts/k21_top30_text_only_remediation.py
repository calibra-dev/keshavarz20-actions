def strip_tags(value: str) -> str:
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", value or "")).strip()

def clean_existing(desc: str) -> str:
    out = re.sub(r"<!-- k21-top30-start -->[\s\S]*?<!-- k21-top30-end -->", "", desc or "", flags=re.I)
    out = re.sub(r"<!-- k21-text-only-start -->[\s\S]*?<!-- k21-text-only-end -->", "", out, flags=re.I)
    out = re.sub(r"<video\b[\s\S]*?</video>", "", out, flags=re.I)
    out = out.replace("<h2>ویدئوی راهنمای این خانواده محصول</h2>", "")
    out = out.replace("<h2>ویدئوی راهنمای انتخاب سایز لوله نخدار</h2>", "")
    return re.sub(r"\n{3,}", "\n\n", out).strip()

def table_rows(attrs, brand, sku):
    rows=[]
    if brand:
        rows.append(("برند ثبت‌شده", brand))
    if sku:
        rows.append(("SKU", sku))
    for a in attrs or []:
        name=(a.get("name") or "").strip()
        vals=a.get("options") or []
        if name and vals:
            rows.append((name, "، ".join(str(v) for v in vals)))
    rows.append(("GTIN / MPN", "در داده معتبر فعلی تأیید نشده؛ شناسه‌ای ساخته نشده است"))
    unique=[]
    seen=set()
    for k,v in rows:
        if k in seen: continue
        seen.add(k); unique.append((k,v))
    return unique

